// Build every picture listed in art/manifest.json into src/pictures/*.json (+ thumbnails) and src/pictures.generated.js
// Usage: node tools/build-pictures.mjs [--only id,id] [--lenient]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { loadFlat, buildPuzzle, makeThumb, BANDS } from './lib/picture.mjs';
import { validatePuzzle } from './lib/validate.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const only = (args.find((a) => a.startsWith('--only=')) || '').slice(7).split(',').filter(Boolean);
const lenient = args.includes('--lenient');
const manifestFile = path.join(root, 'art/manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
fs.mkdirSync(path.join(root, 'src/pictures'), { recursive: true }); fs.mkdirSync(path.join(root, 'art/thumbs'), { recursive: true });
let failures = 0;
const CATS = ['animals', 'unicorns', 'dinosaurs', 'vehicles', 'space', 'fantasy', 'food', 'nature', 'pixel'];
const rows = [];
for (const m of manifest) {
  if (m.kind === 'grid') continue; // Pixel Grid pictures are built by tools/pixel-grid.mjs
  if (only.length && !only.includes(m.id)) continue;
  const band = BANDS[m.diff];
  const { rgba, w, h } = await loadFlat(path.join(root, m.src), band.size, m.bg || [255, 255, 255]);
  const { puzzle, lab } = buildPuzzle(rgba, w, h, m, m.opts || {});
  const problems = validatePuzzle(puzzle);
  const th = await makeThumb(puzzle, lab);
  puzzle.thumb = th.dataUrl;
  fs.writeFileSync(path.join(root, 'src/pictures', m.id + '.json'), JSON.stringify(puzzle));
  fs.writeFileSync(path.join(root, 'art/thumbs', m.id + '.png'), th.full ? await sharp(th.full).resize(256, 256).png().toBuffer() : th.png);
  rows.push(`${m.id.padEnd(22)} ${puzzle.diff.padEnd(6)} regions ${String(puzzle.stats.regions).padStart(3)}  colours ${String(puzzle.stats.colours).padStart(2)}  err ${puzzle.stats.meanErr}  json ${(JSON.stringify(puzzle).length / 1024).toFixed(0)}KB ${problems.length ? '  PROBLEMS: ' + problems.slice(0, 4).join('; ') : ''}`);
  if (problems.length) failures++;
}
console.log(rows.join('\n'));
// generated index (all manifest entries that have a json)
const have = manifest.filter((m) => fs.existsSync(path.join(root, 'src/pictures', m.id + '.json')));
const order = { easy: 0, medium: 1, hard: 2 };
have.sort((a, b) => CATS.indexOf(a.cat) - CATS.indexOf(b.cat) || order[a.diff] - order[b.diff] || a.name.localeCompare(b.name));
const js = '// GENERATED by tools/build-pictures.mjs - do not edit\n' + have.map((m, i) => `import p${i} from './pictures/${m.id}.json';`).join('\n') + `\nexport default [${have.map((_, i) => 'p' + i).join(', ')}];\n`;
fs.writeFileSync(path.join(root, 'src/pictures.generated.js'), js);
console.log(`${have.length} pictures indexed; ${failures} with problems`);
if (failures && !lenient) process.exit(1);
